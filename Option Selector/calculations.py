def firstCalculation(a: int, b: int) -> None:
    """
    Performs a mathematical computation (addition) on two integers
    and renders the result to the console.
    """
    result = a + b
    print(f"The result of the first calculation (addition) is: {result}")

def secondCalculation(a: int, b: int) -> None:
    """
    Performs a mathematical computation (multiplication) on two integers
    and renders the result to the console.
    """
    result = a * b
    print(f"The result of the second calculation (multiplication) is: {result}")